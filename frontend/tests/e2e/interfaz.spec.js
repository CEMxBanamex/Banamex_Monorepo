import { test, expect } from '@playwright/test'

for (const ancho of [1280, 390]) {
  test(`panel compacto sin menú lateral, ancho ${ancho}`, async ({ page }) => {
    await page.setViewportSize({ width: ancho, height: 650 })
    await page.goto('/')
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(page.getByRole('navigation').getByRole('button', { name: 'Asistente', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Abrir asistente' }).click()
    await expect(page.getByRole('heading', { name: '¿En qué puedo ayudarte?' })).toBeInViewport()
    await expect(page.getByText('Consulta políticas, revisa un caso y encuentra la evidencia.', { exact: true })).toBeInViewport()
    const caja = await page.getByLabel('Tu pregunta').boundingBox()
    expect(caja.height).toBeLessThan(60)
    await expect(page.getByRole('button', { name: 'Enviar', exact: true })).toBeInViewport()
    await page.screenshot({ path: `test-results/panel-compacto-${ancho}.png`, fullPage: false })
  })
}

test('panel lateral conserva la página, foco y conversación', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await page.getByRole('button', { name: 'Bitácora', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir asistente', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bitácora', exact: true })).toBeVisible()
  const panel = page.getByRole('complementary', { name: 'Panel del asistente' })
  await expect(panel).toBeVisible()
  const caja = await panel.boundingBox()
  expect(caja.width).toBeGreaterThan(550)
  expect(caja.width).toBeLessThan(750)
  await page.getByLabel('Tu pregunta').fill('Hola')
  await page.getByRole('button', { name: 'Enviar', exact: true }).click()
  await expect(page.locator('.asistente-respuesta')).toContainText('respuesta simulada')
  await page.getByRole('button', { name: 'Cerrar asistente' }).click()
  await page.getByRole('button', { name: 'Abrir asistente' }).click()
  await expect(page.locator('.asistente-respuesta')).toContainText('respuesta simulada')
  await page.getByRole('button', { name: 'Activar modo oscuro' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-tema', 'oscuro')
  await page.screenshot({ path: 'test-results/interfaz-oscuro.png', fullPage: true })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-tema', 'oscuro')
})

test('fecha y caso no se superponen y la tabla se desplaza', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await page.getByRole('button', { name: 'Bitácora', exact: true }).click()
  const fila = page.locator('.tabla.bit tbody tr.click').first()
  await expect(fila).toBeVisible()
  const fecha = await fila.locator('.bit-fecha').boundingBox()
  const caso = await fila.locator('.bit-caso').boundingBox()
  expect(fecha.x + fecha.width).toBeLessThanOrEqual(caso.x + 1)
  await page.screenshot({ path: 'test-results/bitacora-claro.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  const tabla = page.getByRole('region', { name: 'Eventos de bitácora' })
  expect(await tabla.evaluate(e => e.scrollWidth > e.clientWidth)).toBe(true)
  await page.getByRole('button', { name: 'Abrir asistente' }).click()
  await expect(page.getByRole('button', { name: 'Cerrar asistente' })).toBeVisible()
  await page.screenshot({ path: 'test-results/chat-movil.png', fullPage: true })
})
