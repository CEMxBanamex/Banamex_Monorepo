test('la sesión muestra a Mauricio y cambia al cerrar e ingresar con otra persona', async ({ page }) => {
  await solicitar(page, 'mauricio@example.com', 'Mauricio Guerrero')
  await adminEntrar(page)
  await page.getByRole('button', { name: 'Revisar solicitud de Mauricio Guerrero', exact: true }).click()
  await page.getByRole('button', { name: 'Aprobar acceso', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await page.getByLabel('Correo').fill('mauricio@example.com')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.locator('.usuario .nombre')).toHaveText('Mauricio Guerrero')
  await expect(page.locator('.usuario .avatar')).toHaveText('MG')
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await solicitar(page, 'otra@example.com', 'Luisa Pérez')
  await adminEntrar(page)
  await page.getByRole('button', { name: 'Revisar solicitud de Luisa Pérez', exact: true }).click()
  await page.getByRole('button', { name: 'Aprobar acceso', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await page.getByLabel('Correo').fill('otra@example.com')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.locator('.usuario .nombre')).toHaveText('Luisa Pérez')
  await expect(page.locator('.usuario .avatar')).toHaveText('LP')
})
