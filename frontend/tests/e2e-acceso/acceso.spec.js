import { test, expect } from '@playwright/test'

async function adminEntrar(page) {
  await page.getByRole('button', { name: 'Soy administrador', exact: true }).click()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await page.getByRole('button', { name: 'Iniciar sesión como administrador', exact: true }).click()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await page.getByLabel('Correo del administrador').fill('admin.demo@example.com')
  await page.getByRole('button', { name: 'Iniciar sesión como administrador', exact: true }).click()
  await expect(page.locator('.usuario .rol')).toHaveText('Administrador')
  await expect(page.locator('.usuario .correo-usuario')).toHaveText('admin.demo@example.com')
  await expect(page.getByRole('navigation')).toBeVisible()
  await page.getByRole('navigation').getByRole('button', { name: 'Administrador', exact: true }).click()
}

async function solicitar(page, correo, nombre = 'Persona Demo') {
  await page.goto('/')
  await page.getByRole('button', { name: 'Solicitar acceso', exact: true }).click()
  await page.getByLabel('Nombre completo').fill(nombre)
  await page.getByLabel('Correo').fill(correo)
  await page.getByLabel('Área o equipo').fill('Operaciones')
  await page.getByRole('button', { name: 'Enviar solicitud', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tu solicitud está pendiente' })).toBeVisible()
}

for (const width of [1280, 390]) {
  test(`registro pendiente, notificación entre pestañas y aprobación a ${width}`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/')
    const admin = await context.newPage()
    await admin.goto('/')
    await adminEntrar(admin)
    await expect(admin.getByRole('status')).toContainText('0')
    await solicitar(page, 'ana.demo@example.com')
    await expect(admin.getByRole('status')).toContainText('1')
    await expect(page.getByRole('button', { name: 'Entrar a la demostración' })).toHaveCount(0)
    await admin.getByRole('button', { name: 'Revisar solicitud de Persona Demo', exact: true }).click()
    await admin.getByRole('button', { name: 'Aprobar acceso', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Tu acceso fue aprobado' })).toBeVisible()
    await page.screenshot({ path: `test-results/acceso-aprobado-${width}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.getByRole('button', { name: 'Entrar a la demostración', exact: true }).click()
    await expect(page.getByRole('navigation')).toBeVisible()
    await expect(page.getByRole('navigation').getByRole('button', { name: 'Administrador', exact: true })).toHaveCount(0)
    await expect(page.locator('.usuario .nombre')).toHaveText('Persona Demo')
    await expect(page.locator('.usuario .avatar')).toHaveText('PD')
    await expect(page.locator('.usuario .rol')).toHaveText('Analista')
    await expect(page.locator('.usuario .correo-usuario')).toHaveText('ana.demo@example.com')
    const rol = await page.locator('.usuario .rol').boundingBox()
    const correo = await page.locator('.usuario .correo-usuario').boundingBox()
    expect(correo.y).toBeGreaterThanOrEqual(rol.y + rol.height - 1)
    await admin.close()
  })
}

test('rechazo exige motivo y no permite ingresar; persiste al recargar', async ({ page }) => {
  await solicitar(page, 'rechazo@example.com')
  await adminEntrar(page)
  await page.getByRole('button', { name: 'Revisar solicitud de Persona Demo', exact: true }).click()
  await page.getByRole('button', { name: 'Rechazar solicitud', exact: true }).click()
  await expect(page.getByRole('status').last()).toContainText('Escribe el motivo')
  await page.getByLabel('Motivo (obligatorio si rechazas)').fill('Falta validar el área solicitante.')
  await page.getByRole('button', { name: 'Rechazar solicitud', exact: true }).click()
  await page.getByRole('combobox', { name: 'Mostrar', exact: true }).selectOption('rechazado')
  await expect(page.getByText(/Revisado por admin.demo@example.com/)).toBeVisible()
  await page.reload()
  await page.getByLabel('Correo').fill('rechazo@example.com')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Solicitud no aprobada' })).toBeVisible()
  await expect(page.getByText('Motivo: Falta validar el área solicitante.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Entrar a la demostración' })).toHaveCount(0)
})

test('sin registro no entra y no duplica solicitudes', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Correo').fill('sinregistro@example.com')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('aún no tiene acceso')
  await solicitar(page, 'duplicado@example.com')
  await page.getByRole('button', { name: 'Volver al ingreso', exact: true }).click()
  await page.getByRole('button', { name: 'Solicitar acceso', exact: true }).click()
  await page.getByLabel('Nombre completo').fill('Duplicado')
  await page.getByLabel('Área o equipo').fill('Operaciones')
  await page.getByRole('button', { name: 'Enviar solicitud', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('ya tiene una solicitud')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('dsa-accesos-demo-v1')).length)).toBe(1)
})


